class ReleaseGateError(RuntimeError):
    """Raised when committed release evidence is incomplete or inconsistent."""


@dataclass
class GoldenClock:
    current: datetime = GOLDEN_EPOCH

    def now(self) -> datetime:
        return self.current

    async def sleep(self, seconds: float) -> None:
        self.advance(seconds)

    def advance(self, seconds: float) -> None:
        if seconds < 0:
            raise ValueError("golden-session time cannot move backwards")
        self.current += timedelta(seconds=seconds)


@dataclass
class StableUuidFactory:
    node_id: str
    sequence: int = 0

    def __call__(self) -> UUID:
        self.sequence += 1
        return uuid5(NAMESPACE_URL, f"dtt-golden:{self.node_id}:{self.sequence}")


def _factory(node_id: str, clock: GoldenClock) -> EnvelopeFactory:
    return EnvelopeFactory(
        node_id,
        clock,
        boot_id=uuid5(NAMESPACE_URL, f"dtt-golden-boot:{node_id}"),
        uuid_factory=StableUuidFactory(node_id),
    )


def _json_text(value: object) -> str:
    return json.dumps(value, indent=2, sort_keys=True) + "\n"


def _jsonl_text(values: list[dict[str, Any]]) -> str:
    return "".join(
        json.dumps(value, separators=(",", ":"), sort_keys=True) + "\n" for value in values
    )


def _sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


